"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Fragment } from "react";
import { Button } from "@/components/ui/Button";
import { errorMessage } from "@/lib/api/client";
import { comparisonKeys, comparisonsApi, type Interpretation } from "@/lib/api/comparisons";

const POLL_MS = 3000;

const SIGNIFICANCE: Record<NonNullable<Interpretation["significance"]>, { label: string; className: string }> = {
  HIGH: { label: "High significance", className: "bg-rose-100 text-rose-800 dark:bg-rose-950 dark:text-rose-300" },
  MEDIUM: { label: "Medium significance", className: "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-300" },
  LOW: { label: "Low significance", className: "bg-zinc-100 text-zinc-700 dark:bg-zinc-800 dark:text-zinc-300" },
  NONE: { label: "No material change", className: "bg-zinc-100 text-zinc-700 dark:bg-zinc-800 dark:text-zinc-300" },
};

/**
 * The AI interpretation of a section's changes. Styled and labelled distinctly
 * from the factual change list; its markers link to the change cards it cites.
 */
export function InterpretationPanel({ comparisonId, sectionKey }: { comparisonId: number; sectionKey: string }) {
  const queryClient = useQueryClient();
  const key = comparisonKeys.interpretation(comparisonId, sectionKey);
  const { data: interpretation, isPending } = useQuery({
    queryKey: key,
    queryFn: () => comparisonsApi.interpretation(comparisonId, sectionKey),
    refetchInterval: (query) => (query.state.data?.status === "PENDING" ? POLL_MS : false),
  });
  const request = useMutation({
    mutationFn: () => comparisonsApi.requestInterpretation(comparisonId, sectionKey),
    onSuccess: (data) => queryClient.setQueryData(key, data),
  });

  return (
    <section
      aria-label="AI interpretation"
      className="rounded-lg border border-violet-300 bg-violet-50/60 p-4 text-sm dark:border-violet-900 dark:bg-violet-950/30"
    >
      <header className="mb-2 flex flex-wrap items-center justify-between gap-2">
        <p className="text-xs font-medium tracking-wide text-violet-800 uppercase dark:text-violet-300">AI interpretation</p>
        {interpretation?.significance && (
          <span className={`rounded px-1.5 py-0.5 text-xs font-medium ${SIGNIFICANCE[interpretation.significance].className}`}>
            {SIGNIFICANCE[interpretation.significance].label}
          </span>
        )}
      </header>

      {isPending ? null : !interpretation || interpretation.status === "FAILED" ? (
        <div className="flex flex-col gap-2">
          {interpretation?.status === "FAILED" && (
            <p className="text-red-700 dark:text-red-400">{interpretation.detail ?? "The interpretation could not be generated."}</p>
          )}
          <p className="text-zinc-600 dark:text-zinc-400">
            Get an AI explanation of what changed in this section and why it may matter.
          </p>
          <div>
            <Button type="button" variant="secondary" className="h-8 px-3 text-xs" pending={request.isPending} onClick={() => request.mutate()}>
              {interpretation?.status === "FAILED" ? "Try again" : "Explain these changes"}
            </Button>
          </div>
          {request.error && <p role="alert" className="text-red-700 dark:text-red-400">{errorMessage(request.error)}</p>}
        </div>
      ) : interpretation.status === "PENDING" ? (
        <p role="status" className="text-zinc-600 dark:text-zinc-400">
          Generating the interpretation…
        </p>
      ) : interpretation.status === "REFUSED" ? (
        <p className="text-zinc-600 dark:text-zinc-400">The AI model declined to interpret these changes.</p>
      ) : (
        <>
          <p className="leading-7 whitespace-pre-wrap">
            <Annotated text={interpretation.summary ?? ""} citations={interpretation.citations} />
          </p>
          <p className="mt-3 text-xs text-zinc-500">
            Generated by {interpretation.model ?? "an AI model"} from the changes listed below. It may be inaccurate; the
            changes themselves are the factual record.
            {interpretation.changesConsidered !== null &&
              interpretation.changesTotal !== null &&
              interpretation.changesConsidered < interpretation.changesTotal &&
              ` Only the first ${interpretation.changesConsidered} of ${interpretation.changesTotal} changes were considered.`}
          </p>
        </>
      )}
    </section>
  );
}

function Annotated({ text, citations }: { text: string; citations: Interpretation["citations"] }) {
  const byEnd = new Map<number, Interpretation["citations"]>();
  for (const citation of citations) {
    // A marker belongs after the text it supports; clamp offsets that overrun the text.
    const end = Math.min(citation.answerEnd, text.length);
    byEnd.set(end, [...(byEnd.get(end) ?? []), citation]);
  }
  const ends = [...byEnd.keys()].filter((at) => at > 0 && at <= text.length).sort((a, b) => a - b);
  const pieces: React.ReactNode[] = [];
  let position = 0;
  for (const at of ends) {
    pieces.push(<Fragment key={`t${at}`}>{text.slice(position, at)}</Fragment>);
    const seen = new Set<number>();
    pieces.push(
      <sup key={`m${at}`} className="ml-0.5 text-xs">
        {byEnd.get(at)!.filter((c) => !seen.has(c.changeOrdinal) && seen.add(c.changeOrdinal)).map((c) => (
          <a
            key={c.changeOrdinal}
            href={`#change-${c.changeOrdinal}`}
            title={c.verified ? `Change ${c.changeOrdinal}` : `Change ${c.changeOrdinal} — quote not found verbatim`}
            className={c.verified ? "text-violet-700 hover:underline dark:text-violet-300" : "text-amber-700 hover:underline"}
          >
            [change {c.changeOrdinal}]
          </a>
        ))}
      </sup>,
    );
    position = at;
  }
  pieces.push(<Fragment key="rest">{text.slice(position)}</Fragment>);
  return <>{pieces}</>;
}
